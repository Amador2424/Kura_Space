create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  service_type text not null check (service_type in ('virtual', 'in_person')),
  booking_date date not null,
  booking_time time without time zone not null,
  name text not null,
  email text not null,
  phone text not null default '',
  notes text not null default '',
  status text not null default 'confirmed'
    check (status in ('confirmed', 'cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.availability_slots (
  id bigint generated by default as identity primary key,
  service_type text not null check (service_type in ('virtual', 'in_person')),
  slot_date date not null,
  slot_time time without time zone not null,
  is_booked boolean not null default false,
  created_at timestamptz not null default now(),
  unique (service_type, slot_date, slot_time)
);

create table if not exists public.waitlist (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text not null default '',
  service_type text not null default 'in_person'
    check (service_type in ('virtual', 'in_person')),
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  key text primary key,
  value text not null default ''
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  presentation_type text not null default 'before_after'
    check (presentation_type in ('before_after', 'after_only')),
  location text not null default '',
  project_date text not null default '',
  summary text not null default '',
  goals text not null default '',
  what_changed text not null default '',
  client_items text not null default '',
  purchased_items text not null default '',
  constraints_text text not null default '',
  service_format text not null default '',
  featured boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.project_images (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  image_path text not null,
  storage_path text,
  label text not null default 'gallery'
    check (label in ('before', 'after', 'gallery')),
  sort_order integer not null default 0
);

create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  quote text not null,
  author text not null,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists bookings_date_idx
  on public.bookings (booking_date, booking_time);

create index if not exists availability_slots_lookup_idx
  on public.availability_slots (service_type, slot_date, is_booked);

create index if not exists project_images_project_idx
  on public.project_images (project_id, label, sort_order);

