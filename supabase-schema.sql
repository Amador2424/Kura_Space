insert into public.availability_slots (
  service_type, slot_date, slot_time, is_booked
)
select
  'virtual',
  day::date,
  slot_time::time,
  false
from generate_series(
  current_date + 1,
  current_date + 60,
  interval '1 day'
) as day
cross join (
  values ('09:00'), ('10:30'), ('12:00'), ('13:30'), ('15:00')
) as times(slot_time)
where extract(isodow from day) between 1 and 5
on conflict (service_type, slot_date, slot_time) do nothing;

