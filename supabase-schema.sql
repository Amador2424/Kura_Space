  p_name text,
  p_email text,
  p_phone text default '',
  p_service_type text default 'in_person'
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
begin
  if p_service_type not in ('virtual', 'in_person') then
    raise exception 'Invalid service type.';
  end if;

