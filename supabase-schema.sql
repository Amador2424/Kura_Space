create or replace function public.create_booking(
  p_service_type text,
  p_slot_date date,
  p_slot_time time without time zone,
  p_name text,
  p_email text,
  p_phone text default '',
  p_notes text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_slot_id bigint;
  v_booking_id bigint;
begin
  if p_service_type not in ('virtual', 'in_person') then
    raise exception 'Invalid service type.';
  end if;

  if p_slot_date < current_date then
    raise exception 'The selected date is in the past.';
  end if;

  if length(trim(coalesce(p_name, ''))) < 2 then
    raise exception 'Please enter your full name.';
  end if;

  if coalesce(p_email, '') !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$' then
    raise exception 'Please enter a valid email address.';
  end if;

  if p_service_type = 'in_person'
     and coalesce(
       (select value from public.settings where key = 'in_person_status'),
       'fully_booked'
     ) <> 'available' then
    raise exception 'In-person appointments are not currently available.';
  end if;

  select id
  into v_slot_id
  from public.availability_slots
  where service_type = p_service_type
    and slot_date = p_slot_date
    and slot_time = p_slot_time
    and is_booked = false
  for update;

  if v_slot_id is null then
    raise exception 'That time slot is no longer available.';
  end if;

  update public.availability_slots
  set is_booked = true
  where id = v_slot_id;

  insert into public.bookings (
    service_type, booking_date, booking_time,
    name, email, phone, notes, status
  )
  values (
    p_service_type, p_slot_date, p_slot_time,
    trim(p_name), lower(trim(p_email)),
    trim(coalesce(p_phone, '')),
    trim(coalesce(p_notes, '')),
    'confirmed'
  )
  returning id into v_booking_id;

  return v_booking_id;
end;
$$;

revoke all on function public.create_booking(
  text, date, time without time zone, text, text, text, text
) from public;
grant execute on function public.create_booking(
  text, date, time without time zone, text, text, text, text
) to anon, authenticated;

