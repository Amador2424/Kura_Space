create or replace function public.set_booking_status(
  p_booking_id bigint,
  p_status text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_booking public.bookings%rowtype;
  v_slot public.availability_slots%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Unauthorized.';
  end if;

  if p_status not in ('confirmed', 'cancelled') then
    raise exception 'Invalid booking status.';
  end if;

  select *
  into v_booking
  from public.bookings
  where id = p_booking_id
  for update;

  if not found then
    raise exception 'Booking not found.';
  end if;

  if v_booking.status = p_status then
    return;
  end if;

  select *
  into v_slot
  from public.availability_slots
  where service_type = v_booking.service_type
    and slot_date = v_booking.booking_date
    and slot_time = v_booking.booking_time
  for update;

  if p_status = 'cancelled' then
    if v_slot.id is not null then
      update public.availability_slots
      set is_booked = false
      where id = v_slot.id;
    end if;
  else
    if v_slot.id is null then
      raise exception 'The original availability slot no longer exists.';
    end if;

    if v_slot.is_booked then
      raise exception 'That slot has already been booked by someone else.';
    end if;

    update public.availability_slots
    set is_booked = true
    where id = v_slot.id;
  end if;

  update public.bookings
  set status = p_status
  where id = p_booking_id;
end;
$$;

revoke all on function public.set_booking_status(bigint, text) from public;
grant execute on function public.set_booking_status(bigint, text)
  to authenticated;

create or replace function public.save_project(
  p_project jsonb,
  p_images jsonb default '[]'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
  v_title text := trim(coalesce(p_project->>'title', ''));
  v_category text := trim(coalesce(p_project->>'category', ''));
begin
  if not public.is_admin() then
    raise exception 'Unauthorized.';
  end if;

  if v_title = '' or v_category = '' then
    raise exception 'Title and category are required.';
  end if;

  v_id := nullif(p_project->>'id', '')::bigint;

  if v_id is null then
    insert into public.projects (
      title, category, presentation_type, location, project_date,
      summary, goals, what_changed, client_items, purchased_items,
      constraints_text, service_format, featured, sort_order
    )
    values (
      v_title,
      v_category,
      coalesce(nullif(p_project->>'presentation_type', ''), 'before_after'),
      coalesce(p_project->>'location', ''),
      coalesce(p_project->>'project_date', ''),
      coalesce(p_project->>'summary', ''),
      coalesce(p_project->>'goals', ''),
      coalesce(p_project->>'what_changed', ''),
      coalesce(p_project->>'client_items', ''),
      coalesce(p_project->>'purchased_items', ''),
      coalesce(p_project->>'constraints_text', ''),
      coalesce(p_project->>'service_format', ''),
      coalesce((p_project->>'featured')::boolean, false),
      coalesce((p_project->>'sort_order')::integer, 0)
    )
    returning id into v_id;
  else
    if not exists (select 1 from public.projects where id = v_id) then
      raise exception 'Project not found.';
    end if;

    update public.projects
    set
      title = v_title,
      category = v_category,
      presentation_type = coalesce(nullif(p_project->>'presentation_type', ''), presentation_type),
      location = coalesce(p_project->>'location', ''),
      project_date = coalesce(p_project->>'project_date', ''),
      summary = coalesce(p_project->>'summary', ''),
      goals = coalesce(p_project->>'goals', ''),
      what_changed = coalesce(p_project->>'what_changed', ''),
      client_items = coalesce(p_project->>'client_items', ''),
      purchased_items = coalesce(p_project->>'purchased_items', ''),
      constraints_text = coalesce(p_project->>'constraints_text', ''),
      service_format = coalesce(p_project->>'service_format', ''),
      featured = coalesce((p_project->>'featured')::boolean, false),
      sort_order = coalesce((p_project->>'sort_order')::integer, 0)
    where id = v_id;
  end if;

  delete from public.project_images where project_id = v_id;

  insert into public.project_images (
    project_id, image_path, storage_path, label, sort_order
  )
  select
    v_id,
    image->>'image_path',
    nullif(image->>'storage_path', ''),
    coalesce(nullif(image->>'label', ''), 'gallery'),
    coalesce((image->>'sort_order')::integer, 0)
  from jsonb_array_elements(coalesce(p_images, '[]'::jsonb)) as image
  where coalesce(image->>'image_path', '') <> '';

  return v_id;
end;
$$;

revoke all on function public.save_project(jsonb, jsonb) from public;
grant execute on function public.save_project(jsonb, jsonb) to authenticated;

create or replace function public.delete_project(p_project_id bigint)
returns text[]
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_paths text[];
begin
  if not public.is_admin() then
    raise exception 'Unauthorized.';
  end if;

  select coalesce(
    array_agg(storage_path) filter (where storage_path is not null),
    array[]::text[]
  )
  into v_paths
  from public.project_images
  where project_id = p_project_id;

  delete from public.projects where id = p_project_id;

  return v_paths;
end;
$$;

revoke all on function public.delete_project(bigint) from public;
grant execute on function public.delete_project(bigint) to authenticated;

